// Public build-time config: the ONLY values the browser bundle and the static SEO files may
// depend on. Secrets (Telegram token, Turnstile secret) stay in the Pages Function env.
//
// - `node scripts/env.mjs` writes src/app/core/config/public-env.generated.ts (git-ignored);
//   runs before build/start/test.
// - `resolvePublicEnv()` is also imported by scripts/postbuild.mjs (sitemap, robots).
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = 'src/app/core/config/public-env.generated.ts';

/** Cloudflare's documented test site key: always passes, works on any hostname. */
export const TURNSTILE_TEST_SITE_KEY = '1x00000000000000000000AA';
/** Current production origin until a custom domain is connected (then set SITE_URL). */
export const DEFAULT_SITE_URL = 'https://mango-tour.pages.dev';

export function resolvePublicEnv(env = process.env) {
  const turnstileSiteKey = env.TURNSTILE_SITE_KEY?.trim() || TURNSTILE_TEST_SITE_KEY;
  const siteUrl = (env.SITE_URL?.trim() || DEFAULT_SITE_URL).replace(/\/+$/, '');
  if (!/^[\w-]+$/.test(turnstileSiteKey))
    throw new Error('env: TURNSTILE_SITE_KEY looks malformed');
  if (!/^https:\/\/[^/\s]+$/.test(siteUrl)) throw new Error('env: SITE_URL must be https://host');
  return { turnstileSiteKey, siteUrl };
}

async function main() {
  const { turnstileSiteKey, siteUrl } = resolvePublicEnv();
  const source = `// GENERATED by scripts/env.mjs — do not edit, do not commit.
export const PUBLIC_ENV = {
  turnstileSiteKey: ${JSON.stringify(turnstileSiteKey)},
  siteUrl: ${JSON.stringify(siteUrl)},
} as const;
`;
  await mkdir(dirname(OUT), { recursive: true });
  await writeFile(OUT, source);
  const notes = [];
  if (turnstileSiteKey === TURNSTILE_TEST_SITE_KEY) notes.push('Turnstile TEST site key');
  if (siteUrl === DEFAULT_SITE_URL) notes.push(`default SITE_URL ${DEFAULT_SITE_URL}`);
  console.log(`env: wrote ${OUT}${notes.length ? ` (using ${notes.join(', ')})` : ''}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
