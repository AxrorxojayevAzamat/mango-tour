// Writes the PUBLIC build-time config the browser bundle may know about.
// Runs before build/start/test. Only values that are safe to ship to every visitor belong here:
// secrets (Telegram token, Turnstile secret) stay in the Pages Function env — never here.
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';

const OUT = 'src/app/core/config/public-env.generated.ts';

/** Cloudflare's documented test site key: always passes, works on any hostname. */
const TURNSTILE_TEST_SITE_KEY = '1x00000000000000000000AA';
const PLACEHOLDER_SITE_URL = 'https://mangotour.example';

const turnstileSiteKey = process.env.TURNSTILE_SITE_KEY?.trim() || TURNSTILE_TEST_SITE_KEY;
const siteUrl = (process.env.SITE_URL?.trim() || PLACEHOLDER_SITE_URL).replace(/\/+$/, '');

if (!/^[\w-]+$/.test(turnstileSiteKey)) throw new Error('env: TURNSTILE_SITE_KEY looks malformed');
if (!/^https:\/\/[^/\s]+$/.test(siteUrl)) throw new Error('env: SITE_URL must be https://host');

const source = `// GENERATED by scripts/env.mjs — do not edit, do not commit.
export const PUBLIC_ENV = {
  turnstileSiteKey: ${JSON.stringify(turnstileSiteKey)},
  siteUrl: ${JSON.stringify(siteUrl)},
} as const;
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, source);

const notes = [];
if (turnstileSiteKey === TURNSTILE_TEST_SITE_KEY) notes.push('Turnstile TEST site key');
if (siteUrl === PLACEHOLDER_SITE_URL) notes.push('placeholder SITE_URL');
console.log(`env: wrote ${OUT}${notes.length ? ` (using ${notes.join(', ')})` : ''}`);
